export function mergeSpecialSearchIntent(cert: { basic: { slug: string }; searchIntent?: SearchIntentData }): SearchIntentData | undefined {
  const extraItems = SPECIAL_SEARCH_INTENTS[cert.basic.slug] ?? [];
  if (extraItems.length === 0) return cert.searchIntent;

  const currentItems = cert.searchIntent?.items ?? [];
  const seen = new Set(currentItems.map((item) => item.query.trim()));
  const mergedItems = [...currentItems, ...extraItems.filter((item) => !seen.has(item.query.trim()))];

  return {
    ...cert.searchIntent,
    items: mergedItems,
  };
}
